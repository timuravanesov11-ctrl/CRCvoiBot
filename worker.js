async function telegram(env, method, data) {
  const response = await fetch(
    `https://api.telegram.org/bot${env.BOT_TOKEN}/${method}`,
    {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(data)
    }
  );

  const result = await response.json();

  if (!result.ok) {
    throw new Error(result.description || "Ошибка Telegram API");
  }

  return result;
}

async function sendMessage(env, chatId, text) {
  const maxLength = 3900;

  while (text.length > 0) {
    let part = text.slice(0, maxLength);

    if (text.length > maxLength) {
      const newline = part.lastIndexOf("\n");
      if (newline > 1000) {
        part = part.slice(0, newline);
      }
    }

    await telegram(env, "sendMessage", {
      chat_id: chatId,
      text: part
    });

    text = text.slice(part.length);
  }
}

async function generatePrompt(env, idea) {
  const response = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent?key=${encodeURIComponent(env.GEMINI_API_KEY)}`,
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        systemInstruction: {
          parts: [{ text: SYSTEM_PROMPT }]
        },
        contents: [{
          role: "user",
          parts: [{
            text:
              "Создай подробный готовый промпт для Claude по этой идее:\n\n" +
              idea
          }]
        }],
        generationConfig: {
          temperature: 0.7,
          maxOutputTokens: 12000
        }
      })
    }
  );

  const data = await response.json();

  if (!response.ok) {
    const message =
      data?.error?.message || "Неизвестная ошибка Gemini API";
    throw new Error(`Gemini API (${response.status}): ${message}`);
  }

  const result = data?.candidates?.[0]?.content?.parts
    ?.map(part => part.text || "")
    .join("")
    .trim();

  if (!result) {
    throw new Error("Gemini вернул пустой ответ. Попробуй другую идею.");
  }

  return result;
}

async function handleMessage(env, message) {
  const chatId = message.chat.id;
  const text = (message.text || "").trim();

  if (!text) return;

  if (text === "/start") {
    await sendMessage(env, chatId,
      "Привет! Я генератор профессиональных промптов для Claude.\n\n" +
      "Напиши обычными словами идею своего мультфильма.\n\n" +
      "Я передам её Gemini, который подготовит подробное техническое " +
      "задание для Claude: сценарий, персонажи, анимация, озвучка, звук " +
      "и создание готового MP4.\n\n" +
      "Команды:\n/start — начать\n/help — помощь\n/prompt — создать промпт\n\n" +
      "Можешь просто отправить идею следующим сообщением."
    );
    return;
  }

  if (text === "/help") {
    await sendMessage(env, chatId,
      "Как пользоваться ботом:\n\n" +
      "1. Напиши идею мультфильма обычными словами.\n" +
      "2. Gemini подготовит подробный промпт для Claude.\n" +
      "3. Скопируй промпт в Claude.\n" +
      "4. Claude будет выполнять задание по этапам и ждать твоего «ок».\n\n" +
      "Команда /prompt — создать промпт."
    );
    return;
  }

  if (text === "/prompt") {
    await sendMessage(env, chatId,
      "Напиши идею мультфильма следующим сообщением."
    );
    return;
  }

  if (text.startsWith("/")) {
    await sendMessage(env, chatId,
      "Неизвестная команда. Используй /start, /help или /prompt."
    );
    return;
  }

  if (text.length < 5) {
    await sendMessage(env, chatId,
      "Опиши идею немного подробнее — хотя бы несколькими словами."
    );
    return;
  }

  if (text.length > 12000) {
    await sendMessage(env, chatId,
      "Идея слишком длинная. Отправь её короче, максимум 12000 символов."
    );
    return;
  }

  await sendMessage(env, chatId,
    "⏳ Gemini анализирует идею и готовит подробный промпт для Claude..."
  );

  try {
    const prompt = await generatePrompt(env, text);

    await sendMessage(env, chatId,
      "✅ Готово! Вот подробный промпт для Claude:\n\n" + prompt
    );
  } catch (error) {
    console.error("Generation error:", error);

    await sendMessage(env, chatId,
      "❌ Не удалось создать промпт.\n\n" +
      error.message +
      "\n\nПопробуй ещё раз немного позже."
    );
  }
}

export default {
  async fetch(request, env) {
    if (request.method === "GET") {
      return new Response("CRCVoiBot работает через Gemini!");
    }

    if (request.method !== "POST") {
      return new Response("Method not allowed", { status: 405 });
    }

    if (!env.BOT_TOKEN || !env.GEMINI_API_KEY) {
      return new Response("Не настроены BOT_TOKEN или GEMINI_API_KEY", {
        status: 500
      });
    }

    try {
      const update = await request.json();

      if (update.message) {
        await handleMessage(env, update.message);
      }

      return new Response("OK");
    } catch (error) {
      console.error("Worker error:", error);
      return new Response("OK");
    }
  }
};
